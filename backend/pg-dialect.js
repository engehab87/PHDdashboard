'use strict';
/* SQL compatibility layer: translate the project's SQLite-flavoured SQL into
   PostgreSQL. Placeholders (?) become $1..$n, and a handful of SQLite-only
   constructs are rewritten. Kept separate so it can be unit-tested without a
   database server. */

/** Replace ? placeholders outside string literals / comments with $1..$n. */
function replacePlaceholders(sql) {
  let out = '';
  let i = 0;
  let n = 0;
  let state = 'normal'; // normal | single | double | line | block
  while (i < sql.length) {
    const c = sql[i];
    const next = sql[i + 1];
    if (state === 'normal') {
      if (c === "'") { state = 'single'; out += c; i++; continue; }
      if (c === '"') { state = 'double'; out += c; i++; continue; }
      if (c === '-' && next === '-') { state = 'line'; out += '--'; i += 2; continue; }
      if (c === '/' && next === '*') { state = 'block'; out += '/*'; i += 2; continue; }
      if (c === '?') { n++; out += '$' + n; i++; continue; }
      out += c; i++; continue;
    }
    if (state === 'single') {
      if (c === "'" && next === "'") { out += "''"; i += 2; continue; }
      if (c === "'") { state = 'normal'; out += c; i++; continue; }
      out += c; i++; continue;
    }
    if (state === 'double') {
      if (c === '"' && next === '"') { out += '""'; i += 2; continue; }
      if (c === '"') { state = 'normal'; out += c; i++; continue; }
      out += c; i++; continue;
    }
    if (state === 'line') {
      out += c; i++;
      if (c === '\n') state = 'normal';
      continue;
    }
    // block comment
    out += c; i++;
    if (c === '*' && next === '/') { out += '/'; i += 2; state = 'normal'; }
    continue;
  }
  return { sql: out, count: n };
}

/** Rewrite SQLite-specific SQL into PostgreSQL, then number placeholders. */
function translate(input) {
  let sql = String(input || '');

  // Identity columns.
  sql = sql.replace(/INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT/gi, 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  sql = sql.replace(/\bAUTOINCREMENT\b/gi, '');

  // SQLite datetime() helper used throughout the app.
  sql = sql.replace(/datetime\(\s*['"]now['"]\s*\)/gi, "NOW()::text");

  // IFNULL -> COALESCE.
  sql = sql.replace(/\bIFNULL\s*\(/gi, 'COALESCE(');

  // INSERT OR IGNORE -> ON CONFLICT DO NOTHING (no conflict target needed).
  if (/^\s*INSERT\s+OR\s+IGNORE\s+INTO/i.test(sql)) {
    sql = sql.replace(/^(\s*)INSERT\s+OR\s+IGNORE\s+INTO/i, '$1INSERT INTO');
    if (!/ON\s+CONFLICT/i.test(sql)) sql = sql.trim().replace(/;?\s*$/, '') + ' ON CONFLICT DO NOTHING';
  }

  // SQLite's implicit-comma GROUP_CONCAT -> string_agg.
  sql = sql.replace(/GROUP_CONCAT\(\s*(DISTINCT\s+)?([^)]+?)\s*\)/gi, (_m, distinct, expr) =>
    `string_agg(${distinct || ''}${expr}::text, ',')`);

  // last_insert_rowid() -> sequence value of the last insert in the session.
  sql = sql.replace(/\blast_insert_rowid\s*\(\s*\)/gi, 'LASTVAL()');

  // No-op SQLite-only statements.
  sql = sql.replace(/DELETE\s+FROM\s+sqlite_sequence[^;]*/gi, 'SELECT 1 WHERE FALSE');
  sql = sql.replace(/PRAGMA\s+[^;\n]*/gi, 'SELECT 1');

  return replacePlaceholders(sql);
}

module.exports = { translate, replacePlaceholders };
